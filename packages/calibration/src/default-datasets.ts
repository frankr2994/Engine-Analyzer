import { CalibrationDataset } from '@engine-analyzer/contracts';
import { computeCalibrationHash } from './hash.js';

function createDataset(raw: Omit<CalibrationDataset, 'contentHash'>): CalibrationDataset {
  const contentHash = computeCalibrationHash(raw);
  return {
    ...raw,
    contentHash,
  };
}

